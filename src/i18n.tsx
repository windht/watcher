type MessageKey = keyof (typeof messages)["en-US"];
const I18nContext = createContext<Language>("en-US");

export function I18nProvider({ language, children }: { language: Language; children: ReactNode }) {
  return <I18nContext.Provider value={language}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const language = useContext(I18nContext);
  return { language, t: (key: MessageKey) => messages[language][key] };
}
